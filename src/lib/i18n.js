export const locales = ["en", "te"];
export const defaultLocale = "en";
export const hasLocale = (lang) => locales.includes(lang);

// Picks `field_te` for Telugu, falling back to `field_en` when no translation exists.
export function pick(obj, field, lang) {
  if (!obj) return "";
  return (lang === "te" && obj[`${field}_te`]) || obj[`${field}_en`] || "";
}

export function formatDate(date, lang) {
  if (!date) return "";
  return new Date(date).toLocaleDateString(lang === "te" ? "te-IN" : "en-IN", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}

